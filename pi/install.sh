#!/usr/bin/env bash
# Installs `flybrain` as a command and a desktop launcher.
#
#   ./install.sh            install for the current user
#   ./install.sh --uninstall
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN="$HOME/.local/bin"
APPS="$HOME/.local/share/applications"
ICONS="$HOME/.local/share/icons"

if [[ "${1:-}" == "--uninstall" ]]; then
    rm -f "$BIN/flybrain" "$APPS/flybrain.desktop" "$APPS/flybrain-view.desktop" \
          "$HOME/Desktop/flybrain-pokemon.desktop" \
          "$ICONS/flybrain.png"
    echo "removed flybrain command and launchers"
    exit 0
fi

mkdir -p "$BIN" "$APPS" "$ICONS"

cat > "$BIN/flybrain" <<WRAP
#!/usr/bin/env bash
# Generated by $HERE/install.sh
exec python3 "$HERE/flybrain.py" "\$@"
WRAP
chmod +x "$BIN/flybrain"

if [[ -f "$HERE/icon.png" ]]; then
    cp "$HERE/icon.png" "$ICONS/flybrain.png"
fi

cat > "$APPS/flybrain.desktop" <<DESK
[Desktop Entry]
Type=Application
Name=Fly Brain
GenericName=Drosophila whole-brain simulation
Comment=Live visual of 139,255 simulated neurons
Exec=$BIN/flybrain view
Icon=$ICONS/flybrain.png
Terminal=false
Categories=Science;Education;
Keywords=neuroscience;connectome;simulation;
DESK

update-desktop-database "$APPS" 2>/dev/null || true

# Desktop shortcut: the fly plays a brand-new game of Pokémon.
if [[ -d "$HOME/Desktop" ]]; then
    cat > "$HOME/Desktop/flybrain-pokemon.desktop" <<DESK
[Desktop Entry]
Name=Fruit Fly Plays Pokémon
Comment=A simulated fruit fly brain plays Pokémon Ultra Violet, picking up where it left off
Exec=$HERE/play/launch.sh
Icon=$ICONS/flybrain.png
Terminal=false
Type=Application
Categories=Game;
DESK
    chmod +x "$HOME/Desktop/flybrain-pokemon.desktop"
fi

echo "installed:"
echo "  command  $BIN/flybrain"
echo "  launcher $APPS/flybrain.desktop"
case ":$PATH:" in
    *":$BIN:"*) echo "  $BIN is on PATH" ;;
    *) echo
       echo "  NOTE: $BIN is not on your PATH. Add it with:"
       echo "    echo 'export PATH=\"\$HOME/.local/bin:\$PATH\"' >> ~/.bashrc && . ~/.bashrc" ;;
esac
echo
echo "try:  flybrain view"
